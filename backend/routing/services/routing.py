"""Truck route generation.

Provider choice (one provider per trip, so all three routes have comparable travel times):
  * Valhalla `truck` costing — honours gross-weight restrictions and truck speeds. The public
    server caps a request at VALHALLA_MAX_MI of straight-line distance between its locations.
  * OSRM — used for longer trips or when Valhalla is unavailable.
Both are capped at TRUCK_MAX_MPH so ETAs reflect a speed-governed tractor-trailer.

Providers rarely return three genuinely different routes, so missing alternatives are generated by
forcing the route through via points offset perpendicular to the trip axis, then rejecting
candidates that are too slow or overlap an existing route too much.
"""

import itertools
import logging
import re
from collections import Counter
from collections.abc import Callable, Sequence
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass

from django.conf import settings
from django.core.cache import cache

from . import geo
from .geo import Coord
from .http import UpstreamError, session, timeout

logger = logging.getLogger(__name__)

LB_PER_TONNE = 2204.62
MAX_ROUTES = 3
SIMPLIFY_TOLERANCE_MI = 0.015  # ~25 m: visually lossless, typically 5-10x fewer vertices
MAX_DETOUR_RATIO = 1.6  # an alternative may take at most 60% longer than the fastest route
MAX_OVERLAP = 0.8  # alternatives sharing more than 80% of their length are duplicates
VALHALLA_NO_ROUTE_CODES = {170, 171, 442, 443}  # unreachable / no path: retrying elsewhere won't help

# (vertices, drive seconds per segment[, miles driven per road name])
RawRoute = tuple[list[Coord], list[float]] | tuple[list[Coord], list[float], dict[str, float]]
_HIGHWAY = re.compile(r"^(I|US|SR|[A-Z]{2})\s+(\d+[A-Z]?)\b")  # "I 80" -> "I-80", "US 6" -> "US-6"


_DIRECTION = re.compile(r"\s+(North|South|East|West|Northbound|Southbound|Eastbound|Westbound|[NSEW])$", re.I)


def via_label(names: dict[str, float]) -> str:
    """Google-style "via I-80 and I-25": the roads carrying most of the route's miles."""
    merged: Counter[str] = Counter()
    for name, miles in names.items():  # "I 65 South" and "I 65" are the same road
        merged[_DIRECTION.sub("", name.strip())] += miles
    names = merged
    total = sum(names.values())
    if not total:
        return ""
    top = [_HIGHWAY.sub(r"\1-\2", n) for n, mi in Counter(names).most_common(2) if mi >= 0.15 * total]
    return " and ".join(dict.fromkeys(top))


@dataclass(slots=True, frozen=True)
class Route:
    coords: tuple[Coord, ...]
    cum_mi: tuple[float, ...]  # cumulative distance at each vertex
    cum_s: tuple[float, ...]  # cumulative drive time at each vertex
    provider: str
    via: str = ""

    @property
    def distance_mi(self) -> float:
        return self.cum_mi[-1]

    @property
    def duration_s(self) -> float:
        return self.cum_s[-1]

    def locate(self, mile: float) -> tuple[Coord, float]:
        """Position and elapsed drive seconds at a given distance along the route."""
        i, t = geo.interp_index(self.cum_mi, mile)
        (a_lat, a_lon), (b_lat, b_lon) = self.coords[i], self.coords[i + 1]
        point = (a_lat + (b_lat - a_lat) * t, a_lon + (b_lon - a_lon) * t)
        return point, self.cum_s[i] + (self.cum_s[i + 1] - self.cum_s[i]) * t


def build_route(raw: RawRoute, provider: str) -> Route:
    coords, seg_times = raw[0], raw[1]
    names = raw[2] if len(raw) > 2 else {}
    if len(coords) < 2 or len(seg_times) != len(coords) - 1:
        raise UpstreamError(f"{provider} returned malformed route geometry")
    cum_mi = geo.cumulative_miles(coords)
    min_s_per_mi = 3600 / settings.TRUCK_MAX_MPH
    cum_s = [0.0]
    for (a, b), t in zip(itertools.pairwise(cum_mi), seg_times, strict=True):
        cum_s.append(cum_s[-1] + max(t, (b - a) * min_s_per_mi))
    keep = geo.simplify_indices(coords, SIMPLIFY_TOLERANCE_MI)
    return Route(
        coords=tuple(coords[i] for i in keep),
        cum_mi=tuple(cum_mi[i] for i in keep),
        cum_s=tuple(cum_s[i] for i in keep),
        provider=provider,
        via=via_label(names),
    )


def join_legs(first: RawRoute, second: RawRoute) -> RawRoute:
    """Concatenate two legs, trimming an out-and-back spur where they meet at the via point."""
    c1, t1 = list(first[0]), list(first[1])
    c2, t2 = list(second[0]), list(second[1])
    while len(c1) > 1 and len(c2) > 1 and geo.haversine_mi(*c1[-2], *c2[1]) < 0.01:
        c1.pop()
        t1.pop()
        c2.pop(0)
        t2.pop(0)
    names = Counter(first[2] if len(first) > 2 else {})
    names.update(second[2] if len(second) > 2 else {})
    return c1 + c2[1:], t1 + t2, dict(names)


# --- Valhalla -------------------------------------------------------------------------------


def _valhalla_trip(trip: dict) -> RawRoute:
    coords: list[Coord] = []
    seg_times: list[float] = []
    names: Counter[str] = Counter()
    for leg in trip["legs"]:
        shape = geo.decode_polyline(leg["shape"], 6)
        seg_d = [geo.haversine_mi(*a, *b) for a, b in itertools.pairwise(shape)]
        times = [0.0] * len(seg_d)
        # Each maneuver reports its time for a run of shape segments; spread it by segment length.
        for m in leg["maneuvers"]:
            b, e, t = m["begin_shape_index"], m["end_shape_index"], float(m["time"])
            if street := m.get("street_names"):
                names[street[0]] += float(m.get("length", 0))
            if e <= b:
                continue
            run = sum(seg_d[b:e])
            for i in range(b, e):
                times[i] = t * (seg_d[i] / run if run > 0 else 1 / (e - b))
        coords.extend(shape if not coords else shape[1:])
        seg_times.extend(times)
    return coords, seg_times, dict(names)


def _valhalla_request(
    points: Sequence[Coord], tonnes: float, alternates: int, quick: bool = False
) -> list[RawRoute]:
    body = {
        "locations": [
            {"lat": lat, "lon": lon, "type": "break" if i in (0, len(points) - 1) else "through"}
            for i, (lat, lon) in enumerate(points)
        ],
        "costing": "truck",
        "costing_options": {
            "truck": {"weight": tonnes, "top_speed": round(settings.TRUCK_MAX_MPH * 1.609344)}
        },
        "units": "miles",
        "directions_type": "maneuvers",
    }
    if alternates:
        body["alternates"] = alternates
    try:
        resp = session(not quick).post(f"{settings.VALHALLA_URL}/route", json=body, timeout=timeout(quick))
        data = resp.json()
    except Exception as exc:
        raise UpstreamError(f"Valhalla unavailable: {exc}", status=503) from exc
    if resp.status_code == 400 and data.get("error_code") in VALHALLA_NO_ROUTE_CODES:
        raise UpstreamError(f"No truck route found: {data.get('error')}", status=422)
    if not resp.ok or "trip" not in data:
        raise UpstreamError(f"Valhalla error {resp.status_code}: {data.get('error')}", status=503)
    trips = [data["trip"], *(alt["trip"] for alt in data.get("alternates", []))]
    return [_valhalla_trip(t) for t in trips]


def _span_mi(points: Sequence[Coord]) -> float:
    return sum(geo.haversine_mi(*a, *b) for a, b in itertools.pairwise(points))


def valhalla(points: Sequence[Coord], tonnes: float, quick: bool = False) -> list[RawRoute]:
    if len(points) == 2:
        return _valhalla_request(points, tonnes, MAX_ROUTES - 1, quick)
    if _span_mi(points) <= settings.VALHALLA_MAX_MI:
        return _valhalla_request(points, tonnes, 0, quick)
    # Too long for one request: route each leg separately and stitch them together.
    legs = [_valhalla_request(pair, tonnes, 0, quick)[0] for pair in itertools.pairwise(points)]
    joined = legs[0]
    for leg in legs[1:]:
        joined = join_legs(joined, leg)
    return [joined]


# --- OSRM -----------------------------------------------------------------------------------


def osrm(points: Sequence[Coord], _tonnes: float, quick: bool = False) -> list[RawRoute]:
    path = ";".join(f"{lon:.6f},{lat:.6f}" for lat, lon in points)
    params = {
        "overview": "full",
        "geometries": "polyline6",
        "annotations": "duration",
        "steps": "true",  # needed for OSRM to fill in each leg's road-name summary
        "alternatives": str(MAX_ROUTES) if len(points) == 2 else "false",
    }
    try:
        resp = session(not quick).get(
            f"{settings.OSRM_URL}/route/v1/driving/{path}", params=params, timeout=timeout(quick)
        )
        data = resp.json()
    except Exception as exc:
        raise UpstreamError(f"OSRM unavailable: {exc}", status=503) from exc
    if data.get("code") != "Ok":
        status = 422 if data.get("code") in {"NoRoute", "NoSegment"} else 503
        raise UpstreamError(f"No route found: {data.get('message', data.get('code'))}", status=status)
    routes: list[RawRoute] = []
    for r in data["routes"]:
        names: Counter[str] = Counter()
        for leg in r["legs"]:
            for name in filter(None, (n.strip() for n in leg.get("summary", "").split(","))):
                names[name] += leg["distance"] / 1609.344
        routes.append(
            (
                geo.decode_polyline(r["geometry"], 6),
                [t for leg in r["legs"] for t in leg["annotation"]["duration"]],
                dict(names),
            )
        )
    return routes


Provider = Callable[[Sequence[Coord], float, bool], list[RawRoute]]
PROVIDERS: dict[str, Provider] = {"valhalla": valhalla, "osrm": osrm}


# --- Diversity ------------------------------------------------------------------------------


def _cell(lat: float, lon: float, size: float = 0.005) -> tuple[int, int]:
    return int(lat // size), int(lon // size)


def overlap(a: Route, b: Route, step_mi: float = 0.3) -> float:
    """Fraction of route `a` that runs within ~0.35-0.7 mi of route `b`."""
    occupied: set[tuple[int, int]] = set()
    mile = 0.0
    while mile <= b.distance_mi:
        occupied.add(_cell(*b.locate(mile)[0]))
        mile += step_mi
    hits = total = 0
    mile = 0.0
    while mile <= a.distance_mi:
        ci, cj = _cell(*a.locate(mile)[0])
        total += 1
        hits += any((ci + di, cj + dj) in occupied for di in (-1, 0, 1) for dj in (-1, 0, 1))
        mile += step_mi * 2
    return hits / total if total else 1.0


def is_distinct(candidate: Route, accepted: list[Route]) -> bool:
    fastest = min(r.duration_s for r in accepted)
    if candidate.duration_s > fastest * MAX_DETOUR_RATIO:
        return False
    return all(overlap(candidate, r) < MAX_OVERLAP and overlap(r, candidate) < MAX_OVERLAP for r in accepted)


def via_points(origin: Coord, dest: Coord, anchor: Coord) -> list[Coord]:
    """Candidate via points: both sides of the trip axis at two offsets, near-side first."""
    straight = geo.haversine_mi(*origin, *dest)
    axis = geo.bearing_deg(*origin, *dest)
    vias = []
    for ratio in (0.18, 0.32):
        dist = min(250.0, max(3.0, straight * ratio))
        vias += [geo.destination(*anchor, axis + 90, dist), geo.destination(*anchor, axis - 90, dist)]
    return vias


def diversify(
    routes: list[Route], origin: Coord, dest: Coord, provider_name: str, tonnes: float
) -> list[Route]:
    accepted: list[Route] = []
    for r in sorted(routes, key=lambda r: r.duration_s):
        if not accepted or is_distinct(r, accepted):
            accepted.append(r)
    if len(accepted) >= MAX_ROUTES:
        return accepted[:MAX_ROUTES]

    provider = PROVIDERS[provider_name]
    anchor, _ = accepted[0].locate(accepted[0].distance_mi / 2)

    def fetch(via: Coord) -> Route | None:
        try:
            # Alternatives are best-effort: fail fast (no retries, short timeout) instead of stalling.
            return build_route(provider([origin, via, dest], tonnes, True)[0], provider_name)
        except UpstreamError as exc:
            logger.info("Via-point candidate %s rejected: %s", via, exc)
            return None

    vias = via_points(origin, dest, anchor)
    # Probe in pairs (both sides of the axis) to stay polite with public routing servers.
    with ThreadPoolExecutor(max_workers=2) as pool:
        for i in range(0, len(vias), 2):
            for cand in pool.map(fetch, vias[i : i + 2]):
                if cand and len(accepted) < MAX_ROUTES and is_distinct(cand, accepted):
                    accepted.append(cand)
            if len(accepted) >= MAX_ROUTES:
                break
    return sorted(accepted, key=lambda r: r.duration_s)


def get_routes(origin: Coord, dest: Coord, load_lb: float) -> list[Route]:
    """Up to three distinct truck routes, fastest first. Cached: road networks change slowly."""
    tonnes = round((settings.TRUCK_TARE_LB + load_lb) / LB_PER_TONNE * 2) / 2  # 0.5 t buckets
    key = f"route:v4:{origin[0]:.4f},{origin[1]:.4f}:{dest[0]:.4f},{dest[1]:.4f}:{tonnes}"
    if (cached := cache.get(key)) is not None:
        return cached

    provider_name = "valhalla" if _span_mi([origin, dest]) <= settings.VALHALLA_MAX_MI else "osrm"
    try:
        raw = PROVIDERS[provider_name]([origin, dest], tonnes)
    except UpstreamError as exc:
        if exc.status == 422 or provider_name == "osrm":
            raise
        logger.warning("Valhalla failed (%s); falling back to OSRM", exc)
        provider_name = "osrm"
        raw = osrm([origin, dest], tonnes)

    routes = diversify([build_route(r, provider_name) for r in raw], origin, dest, provider_name, tonnes)
    cache.set(key, routes, settings.ROUTE_CACHE_TTL_S)
    return routes
